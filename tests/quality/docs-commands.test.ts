import { afterAll, describe, expect, test } from 'bun:test'
import { mkdirSync, mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { join, resolve } from 'node:path'

const repository = resolve(import.meta.dir, '../..')
const docs = [
  'docs/getting-started.md',
  'docs/developer-tooling.md',
  'docs/standalone-projects.md',
  'docs/consumer-linting.md',
  'docs/toolchain.md',
  'docs/development.md',
] as const

type Command = { path: string; section: string; line: string }

const scripts: Record<string, string> = JSON.parse(
  readFileSync(join(repository, 'package.json'), 'utf8')
).scripts

// Commands inside a generated project run that project's scripts, so generate one with the real CLI.
const cache = join(repository, '.bun-native')
mkdirSync(cache, { recursive: true })
const directory = mkdtempSync(join(cache, 'docs-commands-'))
afterAll(() => rmSync(directory, { recursive: true, force: true }))
const created = Bun.spawnSync(
  [process.execPath, 'scripts/native.ts', 'create', join(directory, 'app')],
  { cwd: repository, stdout: 'pipe', stderr: 'pipe', timeout: 60_000 }
)
const projectScripts: Record<string, string> =
  created.exitCode === 0
    ? JSON.parse(readFileSync(join(directory, 'app/package.json'), 'utf8')).scripts
    : {}

// Subcommands and their accepted flags come from the CLI's own usage text.
const usage = Bun.spawnSync([process.execPath, 'scripts/native.ts', '--help'], {
  cwd: repository,
  stdout: 'pipe',
  stderr: 'pipe',
  timeout: 30_000,
})
const usageText = usage.stdout.toString()
const subcommands = new Set(
  [...usageText.matchAll(/^ {2}bun (?:run native|scripts\/native\.ts) (\w+)/gm)].map(
    (match) => match[1]!
  )
)

// Shell commands from fenced sh blocks, with trailing-backslash continuations joined.
function commands(path: string): Command[] {
  const text = readFileSync(join(repository, path), 'utf8')
  const result: Command[] = []
  let section = ''
  let block: string[] | undefined
  for (const line of text.split('\n')) {
    if (block === undefined) {
      const heading = /^#{1,3} (.+)$/.exec(line)
      if (heading) section = heading[1]!
      else if (/^```(?:sh|bash|shell)$/.test(line)) block = []
      continue
    }
    if (line === '```') {
      let joined = ''
      for (const part of block) {
        joined += part.replace(/\\$/, '').trim() + (part.endsWith('\\') ? ' ' : '\n')
      }
      for (const entry of joined.split('\n'))
        if (entry.trim() !== '') result.push({ path, section, line: entry.trim() })
      block = undefined
    } else block.push(line)
  }
  return result
}

const all = docs.flatMap(commands)

describe('documented shell commands', () => {
  test('the CLI usage lists its subcommands', () => {
    expect(usage.exitCode).toBe(0)
    expect([...subcommands].sort()).toEqual(
      ['build', 'check', 'create', 'dev', 'doctor', 'format', 'lint'].sort()
    )
  })

  test('a project generated by the documented create command has the scripts the docs run', () => {
    expect(created.exitCode).toBe(0)
    for (const name of ['dev', 'build', 'check', 'format', 'format:check', 'lint'])
      expect(projectScripts[name]).toBeDefined()
  })

  test('every documented docs file has commands to check', () => {
    for (const path of ['docs/getting-started.md', 'docs/developer-tooling.md'])
      expect(all.filter((entry) => entry.path === path).length).toBeGreaterThan(0)
  })

  test('bun run names an existing package script, and native names a real subcommand', () => {
    const problems: string[] = []
    for (const { path, line } of all) {
      const match = /^(?:MIMALLOC_PURGE_DELAY=\d+ )?bun run ([\w:-]+)(?: (\w+))?/.exec(line)
      if (!match) continue
      const [, script, subcommand] = match
      if (scripts[script!] === undefined && projectScripts[script!] === undefined)
        problems.push(`${path}: bun run ${script} is not a script`)
      else if (script === 'native' && subcommand && !subcommands.has(subcommand))
        problems.push(`${path}: bun run native ${subcommand} is not a subcommand`)
    }
    expect(problems).toEqual([])
  })

  test('documented native flags are ones the CLI accepts', () => {
    const accepted = new Set([...usageText.matchAll(/--[\w-]+/g)].map((match) => match[0]))
    const problems: string[] = []
    for (const { path, line } of all) {
      if (!/\bbun (?:run native|scripts\/native\.ts)\b/.test(line)) continue
      for (const flag of line.match(/--[\w-]+/g) ?? [])
        if (!accepted.has(flag)) problems.push(`${path}: ${flag} in "${line}"`)
    }
    expect(problems).toEqual([])
  })

  test('the getting-started tutorial never invokes Cargo outside host supply', () => {
    const tutorial = all.filter((entry) => entry.path === 'docs/getting-started.md')
    const withCargo = tutorial.filter((entry) => /\bcargo\b/.test(entry.line))
    expect(withCargo.map((entry) => entry.section)).toEqual([])
    // The prose names `bun run native:build` as the only source build, in the host-supply section.
    const text = readFileSync(join(repository, 'docs/getting-started.md'), 'utf8')
    const mentions = text.split(/^## /m).filter((part) => /\bcargo build\b/.test(part))
    expect(mentions.map((part) => part.split('\n')[0])).toEqual(['2. Supply a native host'])
  })

  test('consumer-project commands never invoke Cargo or a WebView', () => {
    for (const { path, line } of all) {
      if (path === 'docs/development.md') continue
      if (
        /\bbun (?:run native|scripts\/native\.ts) (?:create|dev|build|check|format|lint)\b/.test(
          line
        )
      ) {
        expect(line).not.toMatch(/cargo|webview|electron|tauri/i)
      }
    }
  })

  test('doctor logs the exact operating system and CPU it ran on', () => {
    const result = Bun.spawnSync([process.execPath, 'scripts/native.ts', 'doctor'], {
      cwd: repository,
      stdout: 'pipe',
      stderr: 'pipe',
      timeout: 60_000,
    })
    const output = result.stdout.toString()
    expect(result.exitCode).toBe(0)
    const os = process.platform === 'win32' ? 'windows' : process.platform
    const cpu = process.arch === 'arm64' ? 'arm64' : 'x64'
    expect(output).toContain(`${os}-${cpu}`)
  })
})
