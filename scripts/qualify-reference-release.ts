import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { prepareReferenceRelease } from '../benchmarks/adapters/references/release-plan.ts';
import { runReleaseWorkflow } from '../benchmarks/lib/release-workflow.ts';
const [name, frozenLock, lockSha256, project, destination] = process.argv.slice(2);
if ((name !== 'mirin' && name !== 'butter') || !frozenLock || !lockSha256 || !project || !destination) throw new Error('Usage: bun scripts/qualify-reference-release.ts mirin|butter <frozen-bun.lock> <sha256> <new-private-project> <report.json>');
const output = resolve(destination); await mkdir(dirname(output), { recursive: true });
const plan = await prepareReferenceRelease(name, project, frozenLock, lockSha256);
const report = await runReleaseWorkflow(plan, { workspace: project, output: output + '.commands' });
await writeFile(output, JSON.stringify({ ...report, packagingProfile: 'portable-tar-not-default-native-installer', sourceReferenceAuthenticated: false }, null, 2) + '\n');
console.log(JSON.stringify({ passed: report.passed, fullStageCoverage: report.fullStageCoverage, output }));
if (!report.passed) process.exitCode = 1;
